// Options de recherche : critère de salaire et case « Évaluer avec l'IA » (cochée par défaut).
import { chromium } from 'playwright';
import { execSync } from 'node:child_process';
import { existsSync, unlinkSync } from 'node:fs';
const BASE = process.env.BASE || 'http://localhost:8090';
const LOG = (process.env.E2E_TMP || '/tmp') + '/fake_calls.log';
const ok = (n, c, x = '') => console.log((c ? 'OK   ' : 'FAIL ') + n + (!c && x ? '  ' + x : ''));
const sh = (c) => execSync(c, { encoding: 'utf8' }).trim();
const J = (m, path, body, auth) => JSON.parse(sh(`curl -s -X ${m} ${BASE}${path} -H 'Content-Type: application/json' ${auth ? `-H 'Authorization: ${auth}'` : ''} ${body ? `-d '${JSON.stringify(body)}'` : ''}`));
const su = J('POST', '/api/collections/_superusers/auth-with-password', { identity: 'admin@test.local', password: 'adminpass123' }).token;
const email = 'opts' + Date.now() + '@t.io';
const u = J('POST', '/api/collections/users/records', { email, password: 'password123', passwordConfirm: 'password123' }, su);
const tok = J('POST', `/api/collections/users/impersonate/${u.id}`, null, su).token;
J('PATCH', `/api/collections/users/records/${u.id}`, { profile: { resume: 'Dev', experiences: [{ poste: 'Dev', entreprise: 'X', categorie: 'Emploi', debut: '2024', fin: '', lieu: '', description: 'x' }] } }, tok);
J('POST', '/jr/key', { provider: 'fake', key: 'good' }, tok);
const b = await chromium.launch({ channel: process.env.PW_CHANNEL || 'chrome' });
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
await p.addInitScript(([t, m]) => { localStorage.setItem('pocketbase_auth', JSON.stringify({ token: t, record: m })); }, [tok, { id: u.id, email }]);
const calls = () => existsSync(LOG);
const search = async () => { await p.click('#go'); await p.waitForSelector('.rowitem'); await p.waitForTimeout(2500); return p.locator('.rowitem').count(); };
await p.goto(`${BASE}/#/search`); await p.waitForSelector('#q'); await p.fill('#q', 'développeur');
ok('« Évaluer avec l\'IA » cochée par défaut', await p.isChecked('#ai'));
if (calls()) unlinkSync(LOG);
await p.uncheck('#ai'); await search();
ok('IA décochée : aucun appel au fournisseur', !calls());
ok('IA décochée : salaire et pertinence estimée affichés', (await p.locator('.rowitem .pay').count()) >= 1 && /~/.test(await p.locator('.rowitem .match').first().innerText()));
await p.fill('#smin', '40000'); await p.check('#sreq');
ok('salaire minimum + indiqué uniquement : 1 offre', (await search()) === 1);
await p.check('#ai'); await p.uncheck('#sreq'); await p.fill('#smin', '');
await search(); await p.waitForTimeout(1500);
ok('IA cochée : l\'évaluation a lieu', calls());
// Plusieurs lieux (pastilles) et rayon : la requête envoie « A;B » et le rayon.
await p.goto(`${BASE}/#/search`); await p.waitForSelector('#q');
for (const c of await p.locator('.tagc button').all()) await c.click();
await p.fill('#loc', 'lyo'); await p.waitForSelector('#loc-list li');
await p.screenshot({ path: (process.env.E2E_OUT || '.out') + '/so-sugg.png', clip: { x: 0, y: 100, width: 1280, height: 400 } });
ok('suggestions de communes affichées', (await p.locator('#loc-list li').count()) === 2 && /Lyon\s+Rhône/.test(await p.locator('#loc-list li').first().innerText()), JSON.stringify(await p.locator('#loc-list li').allInnerTexts()));
await p.keyboard.press('ArrowDown'); await p.keyboard.press('Enter');
ok('suggestion choisie au clavier : pastille « Lyon, Rhône »', (await p.locator('.tagc').allInnerTexts()).join().includes('Lyon, Rhône'));
await p.screenshot({ path: (process.env.E2E_OUT || '.out') + '/so-one.png', clip: { x: 0, y: 100, width: 1280, height: 400 } });
ok('un lieu tient sur une ligne', (await p.locator('#loc-box').boundingBox()).height < 60, JSON.stringify(await p.locator('#loc-box').boundingBox()));
await p.click('.tagc button');
await p.fill('#loc', 'Lyon, France'); await p.press('#loc', 'Enter');
await p.fill('#loc', 'Paris'); await p.press('#loc', ';');
await p.fill('#loc', 'Nantes'); // validé à l'envoi
await p.evaluate(() => scrollTo(0, 0)); await p.screenshot({ path: (process.env.E2E_OUT || '.out') + '/so-form.png' });
ok('deux lieux validés en pastilles', (await p.locator('.tagc').count()) === 2);
await p.selectOption('#rad', '50');
const [req] = await Promise.all([p.waitForRequest((r) => r.url().endsWith('/jr/search')), p.click('#go')]);
const body = req.postDataJSON();
ok('lieux envoyés (3 dont celui en cours de saisie) et rayon', body.location === 'Lyon, France;Paris;Nantes' && body.radius === 50, JSON.stringify(body));
await p.waitForSelector('.rowitem');
// Reprise de la dernière recherche et historique.
await p.reload(); await p.waitForSelector('.rowitem');
ok('dernière recherche reprise : champ, résultats et message', (await p.inputValue('#q')) === 'développeur' && (await p.locator('.rowitem').count()) === 12 && /Dernière recherche/.test(await p.innerText('#status')));
ok('historique : une recherche récente proposée', (await p.locator('[data-hist]').count()) >= 1);
await p.screenshot({ path: (process.env.E2E_OUT || '.out') + '/so-recent.png', clip: { x: 0, y: 0, width: 1280, height: 520 } });
await p.fill('#q', 'autre'); 
const [again] = await Promise.all([p.waitForRequest((r) => r.url().endsWith('/jr/search')), p.click('[data-hist]')]);
ok('clic sur une recherche récente : elle est relancée', again.postDataJSON().query === 'développeur', again.postData());
await b.close();
